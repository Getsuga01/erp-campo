WHENEVER SQLERROR EXIT SQL.SQLCODE;

-- Cursor incremental: uma linha por origem de dados. `posicao` guarda a
-- marca-d'água no formato definido pelo integrador (timestamp ISO-8601 UTC).
CREATE TABLE INTEGRACAO.INT_CURSOR (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nome          VARCHAR2(64) NOT NULL,
  posicao       VARCHAR2(64) NOT NULL,
  atualizado_em TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_INT_CURSOR        PRIMARY KEY (id),
  CONSTRAINT UK_INT_CURSOR_NOME   UNIQUE (nome)
);

-- Cabeçalho de cada ciclo/lote de integração.
CREATE TABLE INTEGRACAO.INT_LOTE (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
  status           VARCHAR2(20) DEFAULT 'EM_ANDAMENTO' NOT NULL,
  iniciado_em      TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  fechado_em       TIMESTAMP(6),
  total_recebidos  NUMBER(9) DEFAULT 0 NOT NULL,
  total_gravados   NUMBER(9) DEFAULT 0 NOT NULL,
  total_rejeitados NUMBER(9) DEFAULT 0 NOT NULL,
  total_duplicados NUMBER(9) DEFAULT 0 NOT NULL,
  cursor_inicio    VARCHAR2(64),
  cursor_fim       VARCHAR2(64),
  observacao       VARCHAR2(500),
  CONSTRAINT PK_INT_LOTE         PRIMARY KEY (id),
  CONSTRAINT CK_INT_LOTE_STATUS  CHECK (status IN ('EM_ANDAMENTO', 'CONCLUIDO', 'FALHOU'))
);

-- Rastreabilidade de cada registro recebido (payload original em CLOB).
CREATE TABLE INTEGRACAO.INT_REGISTRO (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
  lote_id          NUMBER        NOT NULL,
  id_origem        VARCHAR2(64)  NOT NULL,
  tipo             VARCHAR2(20)  NOT NULL,
  status           VARCHAR2(20)  DEFAULT 'RECEBIDO' NOT NULL,
  codigo_erro      VARCHAR2(16),
  mensagem_erro    VARCHAR2(500),
  payload_original CLOB          NOT NULL,
  recebido_em      TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  processado_em    TIMESTAMP(6),
  origem           VARCHAR2(20)  DEFAULT 'CICLO' NOT NULL,
  CONSTRAINT PK_INT_REGISTRO          PRIMARY KEY (id),
  CONSTRAINT UK_INT_REGISTRO_ORIGEM   UNIQUE (id_origem),
  CONSTRAINT FK_INT_REGISTRO_LOTE     FOREIGN KEY (lote_id) REFERENCES INTEGRACAO.INT_LOTE (id),
  CONSTRAINT CK_INT_REGISTRO_TIPO     CHECK (tipo IN ('PESAGEM', 'MAQUINA', 'INSUMO')),
  CONSTRAINT CK_INT_REGISTRO_STATUS   CHECK (status IN ('RECEBIDO', 'GRAVADO', 'REJEITADO', 'DUPLICADO', 'PENDENTE_FILA')),
  CONSTRAINT CK_INT_REGISTRO_ORIGEM   CHECK (origem IN ('CICLO', 'REPROCESSAMENTO', 'MANUAL'))
);

-- Índices de apoio (a UK já indexa id_origem; criado índice explícito conforme
-- plano): consultas por lote, por status (painel/fila) e por id_origem.
CREATE INDEX INTEGRACAO.IX_INT_REGISTRO_ID_ORIGEM ON INTEGRACAO.INT_REGISTRO (id_origem);
CREATE INDEX INTEGRACAO.IX_INT_REGISTRO_LOTE      ON INTEGRACAO.INT_REGISTRO (lote_id);
CREATE INDEX INTEGRACAO.IX_INT_REGISTRO_STATUS    ON INTEGRACAO.INT_REGISTRO (status);

EXIT;
