--                 * INT_CURSOR   : cursor incremental por origem (UK por
--                                  `nome`; linha semeada 'CAMPO_API' — ver
--                                  07_carga_mestres.sql).
--                 * INT_LOTE     : cabeçalho de cada ciclo/lote de integração
--                                  com contadores mantidos pelo integrador.
--                 * INT_REGISTRO : rastreabilidade 1:1 de cada apontamento
--                                  recebido; `id_origem` (UK) garante a
--                                  idempotência; `status` alimenta a
--                                  conciliação (views do 06_views.sql).
--               Índices adicionais em id_origem (além da UK), lote_id e
--               status para as consultas do integrador e do painel.
