-- Projeto 2 (demo fictícia) — Integração Sistema de Campo → ERP
--
-- Arquivo ....: 04_apontamento.sql
-- Tarefa .....: 1.5 — Tabela de apontamentos validados (destino no ERP)
-- Objetivo ...: Criar ERP_SUPRIMENTOS.APONTAMENTO_CAMPO, tabela de destino dos
--               apontamentos validados — 1:1 com INT_REGISTRO (registro_id é
--               UK). Pertence ao schema do ERP fictício por ser dado de
--               negócio consolidado.
-- Convenções :
--   * data_hora é gravada em UTC (conversão feita pelo integrador; o
--     container roda com fuso UTC).
--   * PESAGEM -> peso_bruto/peso_tara/peso_liquido preenchidos.
--   * MAQUINA -> equipamento_id e horas_maquina preenchidos.
--   * INSUMO  -> item_id e quantidade preenchidos; equipamento_id é NULL.
--   * As quantidades ficam NULLable por tipo: a checagem de preenchimento
--     por tipo é regra de validação do integrador (Fase 3), não do banco.
--   * id_origem é mantido denormalizado aqui (o UK de idempotência vive em
--     INT_REGISTRO) e recebe índice para consultas de rastreio.
--------------------------------------------------------------------------------
WHENEVER SQLERROR EXIT SQL.SQLCODE;

-- Objetos da demo vivem no PDB XEPDB1 (ver 01_schema.sql); cada script roda
-- em sessão sqlplus nova conectada ao CDB$ROOT — trocar de container aqui.
ALTER SESSION SET CONTAINER = XEPDB1;

-- Privilegio de FK entre schemas: para criar FK apontando para tabela de
-- outro schema, Oracle exige REFERENCES concedido DIRETAMENTE ao DONO da
-- tabela filha (ERP_SUPRIMENTOS) — nem SYSDBA dispensa esse grant, e sem
-- ele o CREATE TABLE falha com ORA-00942. (FK para ITEM dispensa grant:
-- pai e filha pertencem ao mesmo schema.)
GRANT REFERENCES ON INTEGRACAO.INT_REGISTRO TO ERP_SUPRIMENTOS;
GRANT REFERENCES ON INTEGRACAO.TALHAO      TO ERP_SUPRIMENTOS;
GRANT REFERENCES ON INTEGRACAO.EQUIPAMENTO  TO ERP_SUPRIMENTOS;

CREATE TABLE ERP_SUPRIMENTOS.APONTAMENTO_CAMPO (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY,
  registro_id    NUMBER        NOT NULL,
  id_origem      VARCHAR2(64)  NOT NULL,
  tipo           VARCHAR2(20)  NOT NULL,
  data_hora      TIMESTAMP(6)  NOT NULL,
  talhao_id      NUMBER        NOT NULL,
  equipamento_id NUMBER,
  item_id        NUMBER,
  peso_bruto     NUMBER(12, 3),
  peso_tara      NUMBER(12, 3),
  peso_liquido   NUMBER(12, 3),
  horas_maquina  NUMBER(6, 2),
  quantidade     NUMBER(12, 3),
  operador       VARCHAR2(120) NOT NULL,
  observacao     VARCHAR2(500),
  criado_em      TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_APONTAMENTO_CAMPO     PRIMARY KEY (id),
  CONSTRAINT UK_APONTAMENTO_REGISTRO  UNIQUE (registro_id),
  CONSTRAINT FK_APONT_REGISTRO        FOREIGN KEY (registro_id)    REFERENCES INTEGRACAO.INT_REGISTRO (id),
  CONSTRAINT FK_APONT_TALHAO          FOREIGN KEY (talhao_id)      REFERENCES INTEGRACAO.TALHAO (id),
  CONSTRAINT FK_APONT_EQUIPAMENTO     FOREIGN KEY (equipamento_id) REFERENCES INTEGRACAO.EQUIPAMENTO (id),
  CONSTRAINT FK_APONT_ITEM            FOREIGN KEY (item_id)        REFERENCES ERP_SUPRIMENTOS.ITEM (id),
  CONSTRAINT CK_APONT_TIPO           CHECK (tipo IN ('PESAGEM', 'MAQUINA', 'INSUMO'))
);

-- Índice de rastreio por id_origem (o UK real fica em INT_REGISTRO).
CREATE INDEX ERP_SUPRIMENTOS.IX_APONT_ID_ORIGEM ON ERP_SUPRIMENTOS.APONTAMENTO_CAMPO (id_origem);

EXIT;
