-- Tarefa .....: 1.6 — Fila de reprocessamento e histórico de tentativas
-- Objetivo ...: Criar:
--                 * FILA_REPROCESSAMENTO : situação de cada registro rejeitado
--                   recuperável (PENDENTE -> PROCESSANDO -> CONCLUIDA ou
--                   DEAD_LETTER), com contagem e limite de tentativas e a
--                   data da próxima tentativa (backoff).
--                 * INT_TENTATIVA        : histórico imutável de cada
--                   tentativa (automática ou manual) com o resultado.
--------------------------------------------------------------------------------
WHENEVER SQLERROR EXIT SQL.SQLCODE;

CREATE TABLE INTEGRACAO.FILA_REPROCESSAMENTO (
  id                NUMBER GENERATED BY DEFAULT AS IDENTITY,
  registro_id       NUMBER        NOT NULL,
  situacao          VARCHAR2(20)  DEFAULT 'PENDENTE' NOT NULL,
  tentativas        NUMBER(3)     DEFAULT 0 NOT NULL,
  max_tentativas    NUMBER(3)     DEFAULT 3 NOT NULL,
  proxima_tentativa TIMESTAMP(6)  NOT NULL,
  motivo            VARCHAR2(500) NOT NULL,
  criado_em         TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  atualizado_em     TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_FILA_REPROCESSAMENTO PRIMARY KEY (id),
  CONSTRAINT FK_FILA_REGISTRO        FOREIGN KEY (registro_id) REFERENCES INTEGRACAO.INT_REGISTRO (id),
  CONSTRAINT CK_FILA_SITUACAO        CHECK (situacao IN ('PENDENTE', 'PROCESSANDO', 'CONCLUIDA', 'DEAD_LETTER')),
  CONSTRAINT CK_FILA_TENTATIVAS      CHECK (tentativas >= 0)
);

CREATE TABLE INTEGRACAO.INT_TENTATIVA (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
  fila_id          NUMBER        NOT NULL,
  numero_tentativa NUMBER(3)     NOT NULL,
  resultado        VARCHAR2(10)  NOT NULL,
  codigo_erro      VARCHAR2(16),
  acionado_por     VARCHAR2(10)  DEFAULT 'SISTEMA' NOT NULL,
  data_tentativa   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  observacao       VARCHAR2(500),
  CONSTRAINT PK_INT_TENTATIVA        PRIMARY KEY (id),
  CONSTRAINT FK_TENTATIVA_FILA       FOREIGN KEY (fila_id) REFERENCES INTEGRACAO.FILA_REPROCESSAMENTO (id),
  CONSTRAINT CK_TENTATIVA_RESULTADO  CHECK (resultado IN ('SUCESSO', 'FALHA')),
  CONSTRAINT CK_TENTATIVA_ACIONADO  CHECK (acionado_por IN ('SISTEMA', 'MANUAL'))
);

EXIT;
