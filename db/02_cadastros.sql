-- Objetivo ...: Criar os cadastros usados na validação dos apontamentos:
--                 * ERP_SUPRIMENTOS.ITEM   — insumos/produtos do ERP fictício
--                   (referência cruzada com o "Projeto 1").
--                 * INTEGRACAO.TALHAO      — parcelas de campo.
--                 * INTEGRACAO.EQUIPAMENTO — máquinas e veículos.
-- Observação .: as colunas `id` usam IDENTITY; a carga (07_carga_mestres.sql)
--               NÃO informa `id`, garantindo ids determinísticos 1..N na
--               ordem de inserção (a chave de negócio é o `codigo`).
--------------------------------------------------------------------------------
WHENEVER SQLERROR EXIT SQL.SQLCODE;

-- Insumos/produtos do ERP fictício (domínio do "Projeto 1").
CREATE TABLE ERP_SUPRIMENTOS.ITEM (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  codigo    VARCHAR2(16)  NOT NULL,
  descricao VARCHAR2(200) NOT NULL,
  unidade   VARCHAR2(4)   NOT NULL,
  ativo     NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT PK_ITEM             PRIMARY KEY (id),
  CONSTRAINT UK_ITEM_CODIGO      UNIQUE (codigo),
  CONSTRAINT CK_ITEM_UNIDADE     CHECK (unidade IN ('KG', 'L', 'UN', 'SC')),
  CONSTRAINT CK_ITEM_ATIVO       CHECK (ativo IN (0, 1))
);

-- Parcelas de campo (local das operações de pesagem/máquina/insumo).
CREATE TABLE INTEGRACAO.TALHAO (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  codigo    VARCHAR2(16)  NOT NULL,
  descricao VARCHAR2(200) NOT NULL,
  area_ha   NUMBER(10, 2) NOT NULL,
  ativo     NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT PK_TALHAO          PRIMARY KEY (id),
  CONSTRAINT UK_TALHAO_CODIGO   UNIQUE (codigo),
  CONSTRAINT CK_TALHAO_ATIVO    CHECK (ativo IN (0, 1))
);

-- Máquinas e veículos das operações de campo.
CREATE TABLE INTEGRACAO.EQUIPAMENTO (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  codigo    VARCHAR2(16)  NOT NULL,
  descricao VARCHAR2(200) NOT NULL,
  tipo      VARCHAR2(20)  NOT NULL,
  ativo     NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT PK_EQUIPAMENTO         PRIMARY KEY (id),
  CONSTRAINT UK_EQUIPAMENTO_CODIGO  UNIQUE (codigo),
  CONSTRAINT CK_EQUIPAMENTO_TIPO   CHECK (tipo IN ('TRATOR', 'COLHEDORA', 'CAMINHAO', 'PULVERIZADOR', 'OUTRO')),
  CONSTRAINT CK_EQUIPAMENTO_ATIVO  CHECK (ativo IN (0, 1))
);

EXIT;
